export const TRANSLATIONS = Object.freeze({
  de: Object.freeze(de),
  en: Object.freeze(en),
});

let currentLanguage = DEFAULT_LANGUAGE;
const listeners = new Set();

/**
 * Ermittelt die erste unterstützte Sprache aus einer Liste von Sprach-Tags (z. B. navigator.languages).
 * @param {readonly unknown[]} [candidates]
 * @returns {string}
 */
export function detectLanguage(candidates = []) {
  for (const candidate of candidates ?? []) {
    if (typeof candidate !== 'string') continue;
    const base = candidate.trim().toLowerCase().split(/[-_]/)[0];
    if (SUPPORTED_LANGUAGES.includes(base)) return base;
  }
  return DEFAULT_LANGUAGE;
}

/** @returns {string} aktuelle Sprache */
export function getLanguage() {
  return currentLanguage;
}

/**
 * Setzt die aktive Sprache. Nicht unterstützte Werte fallen auf DEFAULT_LANGUAGE zurück.
 * @param {string} language
 * @returns {boolean} true, wenn sich die Sprache geändert hat
 */
export function setLanguage(language) {
  const next = SUPPORTED_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
  if (next === currentLanguage) return false;
  currentLanguage = next;
  for (const listener of listeners) listener(next);
  return true;
}

/**
 * Übersetzt einen Schlüssel; {platzhalter} werden durch params ersetzt.
 * Fallback-Kette: aktuelle Sprache → Englisch → Deutsch → Schlüssel.
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @returns {string}
 */
export function t(key, params) {
  const text = TRANSLATIONS[currentLanguage][key] ?? TRANSLATIONS.en[key] ?? TRANSLATIONS.de[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/**
 * Registriert einen Listener für Sprachwechsel.
 * @param {(language: string) => void} listener
 * @returns {() => void} Abmelde-Funktion
 */
export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}
